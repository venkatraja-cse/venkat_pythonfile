# Python Basics - Sequence of Instructions

# 1. Print Start, Middle, End in order
print("Start")
print("Middle")
print("End")

# 2. Predictable sequence
print("First")
print("Second")
print("Third")

# 3. Change the value of x
x = 10
print(x)
x = 20
print(x)

# 4. Change the value of number
number = 5
print(number)
number = 10
print(number)

# 5. Print A, B, C in order
print("A")
print("B")
print("C")

# 6. Print name followed by age
name = "Ravi"
age = 20
print(name)
print(age)

# 7. Display 1, 2, 3, 4 in order
print(1)
print(2)
print(3)
print(4)

# 8. Print x followed by y
x = 5
y = 10
print(x)
print(y)

# 9. Print Start, calculate 2+3, then print End
print("Start")
print(2 + 3)
print("End")

# 10. Login, Dashboard, Logout
print("Login")
print("Dashboard")
print("Logout")
