# Python Basics - Data Types: int, float, str

# Identify data types
print(type(25))          # int
print(type(25.5))        # float
print(type("25"))        # str

# Integer variable
age = 21
print(age, type(age))

# Float variable
height = 5.8
print(height, type(height))

# String variable
name = "Arun"
print(name, type(name))

# Multiple variables
age = 20
price = 99.5
name = "Ravi"

print(age, type(age))
print(price, type(price))
print(name, type(name))

marks = 90
temperature = 36.5
message = "Welcome"

print(type(marks))
print(type(temperature))
print(type(message))
